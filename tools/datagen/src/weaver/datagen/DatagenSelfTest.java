package weaver.datagen;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.Set;
import java.util.LinkedHashSet;
import java.util.stream.Stream;

/**
 * Dependency-free self-test for the datagen tool.
 *
 * <p>Run through {@code test.ps1}: builds the tool and executes this main class.
 * On success it prints {@code DATAGEN SELFTEST ok=true checks=<n>}; on failure it
 * prints {@code DATAGEN SELFTEST ok=false check=<name> reason=<...>} and exits 1.
 */
public final class DatagenSelfTest
{
    private static int checks;
    private static String currentCheck = "startup";

    private DatagenSelfTest()
    {
    }

    public static void main(String[] args)
    {
        Path temp = null;
        int exit = 0;
        try
        {
            temp = Files.createTempDirectory("weaver-datagen-selftest-");
            runAll(temp);
            System.out.println("DATAGEN SELFTEST ok=true checks=" + checks);
        }
        catch (Throwable failure)
        {
            exit = 1;
            System.out.println("DATAGEN SELFTEST ok=false check=" + currentCheck
                    + " reason=" + oneLine(failure));
        }
        finally
        {
            deleteTree(temp);
        }
        System.exit(exit);
    }

    private static void runAll(Path temp) throws Exception
    {
        check("deterministic-generation", () ->
        {
            String manifest = fullManifest();
            Pack first = generate(temp, "deterministic-a", manifest);
            Pack second = generate(temp, "deterministic-b", manifest);

            requireEquals(first.files().keySet(), second.files().keySet(),
                    "generated file sets differ");
            for (String rel : first.files().keySet())
            {
                require(java.util.Arrays.equals(first.files().get(rel),
                                second.files().get(rel)),
                        "generated bytes differ for " + rel);
            }
            String firstFingerprint = Verifier.fingerprint(first.dir());
            String secondFingerprint = Verifier.fingerprint(second.dir());
            requireEquals(firstFingerprint, secondFingerprint,
                    "fingerprints differ for the same manifest");
            require(Verifier.verify(first.dir()).ok(), "first deterministic pack failed verify");
            require(Verifier.verify(second.dir()).ok(), "second deterministic pack failed verify");
        });

        check("verifier-corrupt-advancement", () ->
        {
            Pack pack = generate(temp, "corrupt-advancement", fullManifest());
            Path copy = copyTree(pack.dir(), temp.resolve("corrupt-advancement-copy"));
            Path advancement = copy.resolve("data/test/advancement/root.json");
            Map<String, Object> root = readObject(advancement);
            root.remove("criteria");
            Files.writeString(advancement, Json.write(root), StandardCharsets.UTF_8);

            Verifier.Report report = Verifier.verify(copy);

            require(!report.ok(), "verifier accepted an advancement without criteria");
            requireContains(joinProblems(report), "criteria",
                    "advancement corruption was not reported as a missing criteria key");
        });

        check("verifier-corrupt-custom-tag", () ->
        {
            Pack pack = generate(temp, "corrupt-custom-tag", fullManifest());
            Path copy = copyTree(pack.dir(), temp.resolve("corrupt-custom-tag-copy"));
            Path tag = copy.resolve("data/test/weaver/tags/testmod/gems/shiny.json");
            Map<String, Object> root = readObject(tag);
            root.put("values", "test:ruby");
            Files.writeString(tag, Json.write(root), StandardCharsets.UTF_8);

            Verifier.Report report = Verifier.verify(copy);

            require(!report.ok(), "verifier accepted a custom tag whose values is a string");
            String problems = joinProblems(report);
            requireContains(problems, "values", "custom tag corruption did not name values");
            requireContains(problems, "expected an array",
                    "custom tag corruption did not report the wrong JSON type");
        });

        check("verifier-full-feature-manifest", () ->
        {
            Pack pack = generate(temp, "full-features", fullManifest());
            Verifier.Report report = Verifier.verify(pack.dir());
            require(report.ok(), "full feature manifest was rejected: " + joinProblems(report));

            Set<String> files = new LinkedHashSet<>(report.files());
            requireContainsFile(files, "assets/test/blockstates/ruby_block.json");
            requireContainsFile(files, "assets/test/models/block/ruby_block.json");
            requireContainsFile(files, "assets/test/models/item/ruby.json");
            requireContainsFile(files, "assets/test/items/ruby.json");
            requireContainsFile(files, "assets/test/lang/en_us.json");
            requireContainsFile(files, "data/test/loot_table/blocks/ruby_block.json");
            requireContainsFile(files, "data/test/recipe/ruby_block.json");
            requireContainsFile(files, "data/test/recipe/ruby_from_block.json");
            requireContainsFile(files, "data/test/tags/block/ruby_blocks.json");
            requireContainsFile(files, "data/test/tags/item/rubies.json");
            requireContainsFile(files, "data/test/weaver/registry/testmod/gems/ruby.json");
            requireContainsFile(files, "data/test/weaver/tags/testmod/gems/shiny.json");
            requireContainsFile(files, "data/test/advancement/root.json");
            requireContainsFile(files, "data/test/advancement/child.json");

            Map<String, Object> withDisplay =
                    readObject(pack.dir().resolve("data/test/advancement/root.json"));
            Map<String, Object> withoutDisplay =
                    readObject(pack.dir().resolve("data/test/advancement/child.json"));
            require(withDisplay.containsKey("display"),
                    "advancement root should have a display");
            require(!withoutDisplay.containsKey("display"),
                    "advancement child should not have a display");
        });

        check("merge-priority", () ->
        {
            Pack low = generate(temp, "merge-low",
                    mergeManifest("Low pack", "Low Gem", "test:low_gem"));
            Pack high = generate(temp, "merge-high",
                    mergeManifest("High pack", "High Gem", "test:high_gem"));
            List<PackMerger.Layer> layers = List.of(
                    new PackMerger.Layer(low.dir(), 5, "low"),
                    new PackMerger.Layer(high.dir(), 10, "high"));

            Path out = temp.resolve("merged");
            PackMerger.Report report = PackMerger.merge(layers, out);

            require(report.ok(), "priority merge failed: " + joinReport(report));
            require(report.conflicts().isEmpty(), "priority merge reported conflicts");
            require(java.util.Arrays.equals(
                            Files.readAllBytes(high.dir().resolve("pack.mcmeta")),
                            Files.readAllBytes(out.resolve("pack.mcmeta"))),
                    "merged pack.mcmeta did not come from the higher layer");
            String lang = Files.readString(out.resolve("assets/test/lang/en_us.json"),
                    StandardCharsets.UTF_8);
            requireContains(lang, "High Gem", "higher-priority lang value did not win");
            require(!lang.contains("Low Gem"), "lower-priority lang value leaked through");

            Map<String, Object> tag = readObject(
                    out.resolve("data/test/weaver/tags/testmod/gems/shiny.json"));
            requireEquals(List.of("test:high_gem", "test:low_gem"), tag.get("values"),
                    "merged tag values are not high-priority first");
            requireEquals(Boolean.TRUE, tag.get("replace"),
                    "merged tag is missing replace=true");
            requireEquals(10L, ((Number) tag.get("priority")).longValue(),
                    "merged tag priority is not the highest layer priority");

            Path outAgain = temp.resolve("merged-again");
            PackMerger.Report reportAgain = PackMerger.merge(layers, outAgain);
            require(reportAgain.ok(), "second merge failed: " + joinReport(reportAgain));
            requireEquals(report.fingerprint(), reportAgain.fingerprint(),
                    "merging the same layers twice produced different fingerprints");
        });

        check("merge-equal-priority-conflict", () ->
        {
            Pack first = generate(temp, "conflict-first",
                    mergeManifest("First pack", "First Gem", "test:first_gem"));
            Pack second = generate(temp, "conflict-second",
                    mergeManifest("Second pack", "Second Gem", "test:second_gem"));
            List<PackMerger.Layer> layers = List.of(
                    new PackMerger.Layer(first.dir(), 7, "first"),
                    new PackMerger.Layer(second.dir(), 7, "second"));

            PackMerger.Report report =
                    PackMerger.merge(layers, temp.resolve("conflict-merged"));

            require(!report.ok(), "equal-priority merge with different pack.mcmeta was accepted");
            require(!report.conflicts().isEmpty(), "conflict list is empty");
            require(report.conflicts().stream().anyMatch(conflict ->
                            conflict.contains("pack.mcmeta")),
                    "pack.mcmeta conflict was not reported: " + report.conflicts());
        });

        check("manifest-rejects-duplicate-ids", () ->
        {
            expectInvalid(Json.obj(
                            "namespace", "test",
                            "blocks", Json.arr(
                                    Json.obj("id", "gem_block", "name", "Gem Block"),
                                    Json.obj("id", "gem_block", "name", "Other Block"))),
                    "duplicate block id", "'gem_block'");

            expectInvalid(Json.obj(
                            "namespace", "test",
                            "items", Json.arr(
                                    Json.obj("id", "gem", "name", "Gem"),
                                    Json.obj("id", "gem", "name", "Other Gem"))),
                    "duplicate item id", "'gem'");

            expectInvalid(Json.obj(
                            "namespace", "test",
                            "advancements", Json.arr(
                                    Json.obj("id", "root"),
                                    Json.obj("id", "root"))),
                    "duplicate advancement id", "'root'");

            expectInvalid(Json.obj(
                            "namespace", "test",
                            "registries", Json.arr(
                                    Json.obj("id", "testmod:gems", "entries", Json.arr()),
                                    Json.obj("id", "testmod:gems", "entries", Json.arr()))),
                    "duplicate registry id", "'testmod:gems'");

            expectInvalid(Json.obj(
                            "namespace", "test",
                            "registries", Json.arr(
                                    Json.obj("id", "testmod:gems", "entries", Json.arr(
                                            Json.obj("id", "ruby", "data", Json.obj()),
                                            Json.obj("id", "ruby", "data", Json.obj()))))),
                    "duplicate entry id", "'ruby'");
        });

        check("manifest-rejects-vanilla-tag-priority", () ->
        {
            expectInvalid(Json.obj(
                            "namespace", "test",
                            "tags", Json.obj(
                                    "block", Json.obj(
                                            "gems", Json.obj(
                                                    "values", Json.arr("test:gem"),
                                                    "priority", 5)))),
                    "vanilla tag directories", "do not support priority");
        });

        check("manifest-rejects-display-and-frame", () ->
        {
            expectInvalid(Json.obj(
                            "namespace", "test",
                            "advancements", Json.arr(
                                    Json.obj("id", "root", "title", "Only Title"))),
                    "title, description and icon", "must be declared together");

            expectInvalid(Json.obj(
                            "namespace", "test",
                            "advancements", Json.arr(Json.obj(
                                    "id", "root",
                                    "title", "Root",
                                    "description", "Gets a gem",
                                    "icon", "test:gem",
                                    "frame", "legendary"))),
                    "frame", "is not one of task|goal|challenge");
        });

        check("merge-tag-dedupe", () ->
        {
            Pack low = generate(temp, "dedupe-low",
                    tagManifest("Low pack", "Low Gem",
                            List.of("test:gem_a", "test:gem_b")));
            Pack high = generate(temp, "dedupe-high",
                    tagManifest("High pack", "High Gem",
                            List.of("test:gem_b", "test:gem_c")));
            List<PackMerger.Layer> layers = List.of(
                    new PackMerger.Layer(low.dir(), 5, "low"),
                    new PackMerger.Layer(high.dir(), 10, "high"));

            Path out = temp.resolve("dedupe-merged");
            PackMerger.Report report = PackMerger.merge(layers, out);

            require(report.ok(), "tag dedupe merge failed: " + joinReport(report));
            Map<String, Object> tag = readObject(
                    out.resolve("data/test/weaver/tags/testmod/gems/shiny.json"));
            requireEquals(List.of("test:gem_b", "test:gem_c", "test:gem_a"),
                    tag.get("values"), "merged tag values were not deduplicated high-first");
            requireEquals(3, ((List<?>) tag.get("values")).size(),
                    "merged tag still contains duplicate values");
        });
    }

    private static void check(String name, Check body) throws Exception
    {
        currentCheck = name;
        body.run();
        checks++;
    }

    @FunctionalInterface
    private interface Check
    {
        void run() throws Exception;
    }

    private record Pack(Path dir, Map<String, byte[]> files)
    {
    }

    private static Pack generate(Path root, String name, String manifestJson) throws IOException
    {
        Path dir = root.resolve(name);
        Files.createDirectories(dir);
        Path manifestFile = root.resolve(name + ".manifest.json");
        Files.writeString(manifestFile, manifestJson, StandardCharsets.UTF_8);
        Manifest manifest = Manifest.load(manifestFile);
        Map<String, byte[]> files = Generator.generate(manifest);
        for (Map.Entry<String, byte[]> entry : files.entrySet())
        {
            Path target = dir.resolve(entry.getKey());
            if (target.getParent() != null)
            {
                Files.createDirectories(target.getParent());
            }
            Files.write(target, entry.getValue());
        }
        Files.writeString(dir.resolve(".weaver-datagen"),
                "generated by tools/weaver-datagen - safe to delete\n",
                StandardCharsets.UTF_8);
        return new Pack(dir, files);
    }

    private static Path copyTree(Path source, Path target) throws IOException
    {
        try (Stream<Path> walk = Files.walk(source))
        {
            for (Path path : walk.sorted().toList())
            {
                Path destination = target.resolve(source.relativize(path).toString());
                if (Files.isDirectory(path))
                {
                    Files.createDirectories(destination);
                }
                else
                {
                    Files.createDirectories(destination.getParent());
                    Files.copy(path, destination, StandardCopyOption.REPLACE_EXISTING);
                }
            }
        }
        return target;
    }

    private static void deleteTree(Path root)
    {
        if (root == null)
        {
            return;
        }
        try (Stream<Path> walk = Files.walk(root))
        {
            List<Path> paths = walk.sorted(Comparator.reverseOrder()).toList();
            for (Path path : paths)
            {
                try
                {
                    Files.deleteIfExists(path);
                }
                catch (IOException ignored)
                {
                }
            }
        }
        catch (IOException ignored)
        {
        }
    }

    private static Map<String, Object> readObject(Path file) throws IOException
    {
        return Json.asObject(Json.parse(
                Files.readString(file, StandardCharsets.UTF_8)), file.toString());
    }

    private static void expectInvalid(Map<String, Object> manifest, String... needles)
    {
        try
        {
            Manifest.parse(manifest);
        }
        catch (Manifest.Invalid invalid)
        {
            String joined = String.join(" | ", invalid.errors());
            for (String needle : needles)
            {
                requireContains(joined, needle,
                        "manifest rejection did not contain '" + needle + "'");
            }
            return;
        }
        throw new IllegalStateException("manifest was accepted but should have been rejected: "
                + needles[0]);
    }

    private static String joinProblems(Verifier.Report report)
    {
        return String.join(" | ", report.problems());
    }

    private static String joinReport(PackMerger.Report report)
    {
        List<String> parts = new ArrayList<>();
        for (PackMerger.Problem problem : report.problems())
        {
            parts.add(problem.toString());
        }
        parts.addAll(report.conflicts());
        return String.join(" | ", parts);
    }

    private static void requireContainsFile(Set<String> files, String rel)
    {
        require(files.contains(rel), "generated tree is missing " + rel);
    }

    private static void requireContains(String haystack, String needle, String message)
    {
        require(haystack != null && haystack.contains(needle), message);
    }

    private static void requireEquals(Object expected, Object actual, String message)
    {
        if (!Objects.equals(expected, actual))
        {
            throw new IllegalStateException(message + " expected=" + expected
                    + " actual=" + actual);
        }
    }

    private static void require(boolean condition, String message)
    {
        if (!condition)
        {
            throw new IllegalStateException(message);
        }
    }

    private static String oneLine(Throwable failure)
    {
        String message = failure.getMessage();
        return (message == null ? failure.getClass().getSimpleName() : message)
                .replace('\n', ' ').replace('\r', ' ');
    }

    private static String mergeManifest(String description, String itemName, String tagValue)
    {
        return Json.write(Json.obj(
                "namespace", "test",
                "description", description,
                "items", Json.arr(Json.obj("id", "gem", "name", itemName)),
                "tags", Json.obj(
                        "testmod:gems", Json.obj(
                                "shiny", Json.obj(
                                        "values", Json.arr(tagValue))))));
    }

    private static String tagManifest(String description, String itemName, List<String> values)
    {
        return Json.write(Json.obj(
                "namespace", "test",
                "description", description,
                "items", Json.arr(Json.obj("id", "gem", "name", itemName)),
                "tags", Json.obj(
                        "testmod:gems", Json.obj(
                                "shiny", Json.obj(
                                        "values", new ArrayList<Object>(values))))));
    }

    private static String fullManifest()
    {
        return """
                {
                  "namespace": "test",
                  "description": "Datagen self test pack",
                  "blocks": [
                    {"id": "ruby_block", "name": "Ruby Block"}
                  ],
                  "items": [
                    {"id": "ruby", "name": "Ruby", "model": "handheld"}
                  ],
                  "recipes": [
                    {"id": "ruby_block", "type": "shaped", "pattern": ["RR", "RR"],
                     "key": {"R": "test:ruby"}, "result": "test:ruby_block", "count": 1},
                    {"id": "ruby_from_block", "type": "shapeless",
                     "ingredients": ["test:ruby_block"], "result": "test:ruby", "count": 9}
                  ],
                  "advancements": [
                    {"id": "root", "title": "Root", "description": "Get a ruby",
                     "icon": "test:ruby", "frame": "task",
                     "background": "minecraft:textures/gui/advancements/backgrounds/stone.png",
                     "show_toast": true, "announce_to_chat": true},
                    {"id": "child", "parent": "test:root"}
                  ],
                  "registries": [
                    {"id": "testmod:gems", "entries": [
                      {"id": "ruby", "data": {"color": "red", "hardness": 7}},
                      {"id": "sapphire", "data": {"color": "blue", "hardness": 8}}
                    ]}
                  ],
                  "tags": {
                    "block": {"ruby_blocks": ["test:ruby_block"]},
                    "item": {"rubies": {"values": ["test:ruby"], "replace": true}},
                    "testmod:gems": {"shiny": {"values": ["test:ruby", "test:sapphire"],
                     "priority": 10, "replace": true}}
                  }
                }
                """;
    }
}
