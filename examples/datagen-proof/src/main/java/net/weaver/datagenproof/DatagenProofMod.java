package net.weaver.datagenproof;

import net.minecraft.core.registries.Registries;
import net.minecraft.resources.Identifier;
import net.minecraft.resources.ResourceKey;
import net.minecraft.server.MinecraftServer;
import net.minecraft.world.item.crafting.Recipe;
import net.minecraft.world.level.storage.LevelResource;
import net.weaver.api.ModContext;
import net.weaver.api.WeaverMod;
import net.weaver.api.event.events.ServerStartedEvent;
import net.weaver.api.registry.DataRegistry;
import net.weaver.api.registry.DataRegistryCodec;
import net.weaver.api.registry.DataRegistryManager;
import net.weaver.api.registry.RegistryKey;
import net.weaver.api.registry.RegistryManager;
import net.weaver.api.registry.TagKey;
import net.weaver.api.registry.WeaverRegistries;
import net.weaver.api.registry.event.DataRegistryRegisterEvent;
import net.weaver.core.registry.DataPackLoader;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.stream.Stream;

/**
 * Generates a data pack with the standalone datagen tool and proves that a
 * registry entry generated by the tool reaches the runtime data registry.
 */
public final class DatagenProofMod implements WeaverMod {

    public record Gem(String color, int hardness) {
    }

    private static final String NAMESPACE = "datagenproof";
    private static final String REGISTRY_ID = "datagenproof:gems";
    private static final String PACK_ID = "datagen-proof";
    private static final int PACK_PRIORITY = 10;

    private static final DataRegistryCodec<Gem> GEM_CODEC = (entryId, data) ->
    {
        final Object color = data.get("color");
        final Object hardness = data.get("hardness");
        if (!(color instanceof String colorText) || !(hardness instanceof Number number)) {
            throw new IllegalArgumentException("gem entry " + entryId
                    + " needs a string color and a numeric hardness");
        }
        return new Gem(colorText, number.intValue());
    };

    private static DataRegistry<Gem> registry;

    @Override
    public void onInitialize(ModContext context) {
        registry = DataRegistryManager.create(REGISTRY_ID, Gem.class, GEM_CODEC);
        context.events().addListener(DataRegistryRegisterEvent.class, event ->
        {
            if (REGISTRY_ID.equals(event.registryId())
                    && registry.get("datagenproof:programmatic") == null) {
                event.register("datagenproof:programmatic", new Gem("green", 1));
            }
        });
        DataRegistryManager.beginRegistration();
        context.events().addListener(ServerStartedEvent.class,
                event -> onServerStarted(context, event));
        context.log("DATAGEN PROOF INIT registry=" + REGISTRY_ID);
    }

    @Override
    public void onRegister(ModContext context) {
        DatagenProofContent.init();
        context.log("DATAGEN PROOF CONTENT ok=true block=" + DatagenProofContent.GEM_BLOCK.id()
                + " items=" + DatagenProofContent.RUBY.id() + ","
                + DatagenProofContent.GEM_BLOCK_ITEM.id());
    }

    private static void onServerStarted(ModContext context, ServerStartedEvent event) {
        final MinecraftServer server = (MinecraftServer) event.server();
        try {
            verify(context, server);
            System.out.println("DATAGEN PROOF ok=true");
        } catch (CheckFailure failure) {
            System.out.println("DATAGEN PROOF CHECK ok=false " + failure.name()
                    + " reason=" + failure.getMessage());
            System.out.println("DATAGEN PROOF ok=false");
        } catch (Throwable failure) {
            System.out.println("DATAGEN PROOF CHECK ok=false runtime reason=" + failure);
            System.out.println("DATAGEN PROOF ok=false");
        }
    }

    private static void verify(ModContext context, MinecraftServer server) throws IOException {
        final Path pack = server.getWorldPath(LevelResource.DATAPACK_DIR).resolve(PACK_ID);
        context.log("DATAGEN PROOF PACK path=" + pack);

        final Path mcmeta = pack.resolve("pack.mcmeta");
        final Path rubyEntry = pack.resolve(
                "data/datagenproof/weaver/registry/datagenproof/gems/ruby.json");
        final Path advancementDir = pack.resolve("data/datagenproof/advancement");
        final Path lootDir = pack.resolve("data/datagenproof/loot_table");
        final Path recipeDir = pack.resolve("data/datagenproof/recipe");

        check(Files.isRegularFile(mcmeta), "pack.mcmeta", "missing " + mcmeta);
        check(Files.isRegularFile(rubyEntry), "registry entry", "missing " + rubyEntry);
        final long advancements = countJson(advancementDir);
        final long lootTables = countJson(lootDir);
        final long recipes = countJson(recipeDir);
        check(advancements >= 1, "advancement files", "no json under " + advancementDir);
        check(lootTables >= 1, "loot table files", "no json under " + lootDir);
        check(recipes >= 1, "recipe files", "no json under " + recipeDir);
        System.out.println("DATAGEN PROOF PACK path=" + pack + " advancement=" + advancements
                + " loot_table=" + lootTables + " recipe=" + recipes);

        final DataPackLoader.Report report = DataPackLoader.read(pack, PACK_ID, PACK_PRIORITY);
        for (String problem : report.problems()) {
            context.log("DATAGEN PROOF PACK PROBLEM " + problem);
        }
        check(report.problems().isEmpty(), "pack problems", report.problems().toString());

        final DataRegistryManager.ApplyReport applied =
                DataRegistryManager.apply(report.snapshot());
        for (String problem : applied.problems()) {
            context.log("DATAGEN PROOF APPLY PROBLEM " + problem);
        }
        check(applied.problems().isEmpty(), "apply problems", applied.problems().toString());

        final DataRegistryManager.FreezeReport freeze = DataRegistryManager.freezeAll();
        check(freeze.isComplete(), "freeze complete", "failures=" + freeze.failures());

        final Gem ruby = registry.get("datagenproof:ruby");
        check(new Gem("red", 7).equals(ruby), "ruby", "got " + ruby);
        final Gem sapphire = registry.get("datagenproof:sapphire");
        check(new Gem("blue", 9).equals(sapphire), "sapphire", "got " + sapphire);
        final Gem programmatic = registry.get("datagenproof:programmatic");
        check(new Gem("green", 1).equals(programmatic), "programmatic", "got " + programmatic);
        System.out.println("DATAGEN PROOF REGISTRY ruby=" + ruby.color() + "/" + ruby.hardness());
        System.out.println("DATAGEN PROOF REGISTRY sapphire=" + sapphire.color() + "/"
                + sapphire.hardness());
        System.out.println("DATAGEN PROOF REGISTRY programmatic=" + programmatic.color() + "/"
                + programmatic.hardness());

        final TagKey<Gem> shiny = TagKey.of(RegistryKey.of(NAMESPACE, "gems"),
                "datagenproof:shiny");
        final int tagSize = registry.tag(shiny).size();
        check(tagSize == 2, "tag size", "expected 2, got " + tagSize);
        System.out.println("DATAGEN PROOF TAG size=" + tagSize);

        check(RegistryManager.registry(WeaverRegistries.ITEM)
                .containsKey("datagenproof:ruby"), "item registered",
                "datagenproof:ruby is missing from minecraft:item");

        final Identifier recipeId =
                Identifier.fromNamespaceAndPath(NAMESPACE, "gem_block");
        final ResourceKey<Recipe<?>> recipeKey =
                ResourceKey.create(Registries.RECIPE, recipeId);
        final boolean recipeLoaded = server.getRecipeManager().byKey(recipeKey).isPresent();
        check(recipeLoaded, "vanilla recipe loaded",
                "recipe " + recipeId + " is missing from the server recipe manager");
        final boolean advancementLoaded = server.getAdvancements()
                .get(Identifier.fromNamespaceAndPath(NAMESPACE, "root")) != null;
        check(advancementLoaded, "vanilla advancement loaded",
                "advancement " + NAMESPACE + ":root is missing from the server");
        System.out.println("DATAGEN PROOF VANILLA recipe=true advancement=true");
        System.out.println("DATAGEN PROOF ADVANCEMENT ok=true");
    }

    private static long countJson(Path directory) throws IOException {
        if (!Files.isDirectory(directory)) {
            return 0;
        }
        try (Stream<Path> paths = Files.walk(directory)) {
            return paths.filter(Files::isRegularFile)
                    .filter(path -> path.getFileName().toString().endsWith(".json"))
                    .count();
        }
    }

    private static void check(boolean condition, String name, String reason) {
        if (!condition) {
            throw new CheckFailure(name, reason);
        }
    }

    private static final class CheckFailure extends RuntimeException {
        private final String name;

        private CheckFailure(String name, String reason) {
            super(reason);
            this.name = name;
        }

        private String name() {
            return name;
        }
    }
}
