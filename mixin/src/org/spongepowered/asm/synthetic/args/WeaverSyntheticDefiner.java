package org.spongepowered.asm.synthetic.args;

import java.lang.invoke.MethodHandles;

/**
 * Defines Mixin's generated helper classes in the {@code org.spongepowered.asm.synthetic.args}
 * package.
 *
 * <p>{@code @ModifyArgs} makes Mixin generate {@code Args$N} classes in this package, and the woven
 * target links against them directly. ModLauncher defines them inside its transformation
 * classloader; a plain agent has no such hook, and {@code MethodHandles.Lookup#defineClass} only
 * defines classes in the package of the lookup class. This class exists for that package, so a host
 * can hand the generated bytes to {@link #define(byte[])} from any loader that can see this class.
 *
 * <p>Weaver never ships a class with a name Mixin generates: this is only the entry point.
 */
public final class WeaverSyntheticDefiner {

    private WeaverSyntheticDefiner() {
    }

    /** Defines one class whose package is {@code org.spongepowered.asm.synthetic.args}. */
    public static Class<?> define(byte[] bytes) throws IllegalAccessException {
        return MethodHandles.lookup().defineClass(bytes);
    }
}
